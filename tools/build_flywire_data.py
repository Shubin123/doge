#!/usr/bin/env python3
"""
Build src/game/flywire_data.lua, the game's copy of flywire-swarm's data
(github.com/Shubin123/flywire-swarm): its reduced FlyWire v783 connectome (618
cell types x hemisphere, 9,144 signed edges) and a sample of the real neurons'
positions, for the Connectome boss's brain (game/swarmBoss.lua).

Usage: python3 tools/build_flywire_data.py [path/to/flywire-swarm]
"""
import json
import os
import random
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SWARM = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "..", "flywire-swarm")
OUT = os.path.join(HERE, "..", "src", "game", "flywire_data.lua")

PER_NODE = 3      # neurons kept per cell type, so every node can be seen firing
WIRED = 2000      # neurons in the graph, in all
UNWIRED = 900     # and ones outside it (the brain's shape, always dim)
QUANT = 999       # positions to ints 0..QUANT (compact)
NOT_IN_GRAPH = 65535

with open(os.path.join(SWARM, "data", "connectome.json")) as f:
    conn = json.load(f)
nodes, edges = conn["nodes"], conn["edges"]
index = {nd["id"]: i for i, nd in enumerate(nodes)}


def both(cell_type):
    return [index.get(cell_type + "|left", -1), index.get(cell_type + "|right", -1)]


io = {
    "sugar": both("GRN_sugar"), "bitter": both("GRN_bitter"), "orn": both("ORN"), "loom": both("LPLC2"),
    "mech": both("JO_mechano"), "pfl3": both("PFL3"), "dna02": both("DNa02"), "dna01": both("DNa01"),
    "gf": both("GF"), "mdn": both("MDN"), "p9": both("DNp09"), "mn9": both("MN9"),
}
oa = [i for i, nd in enumerate(nodes) if nd["type"].startswith("OA-")]

with open(os.path.join(SWARM, "data", "neurons.json")) as f:
    count = json.load(f)["count"]
with open(os.path.join(SWARM, "data", "neurons.bin"), "rb") as f:
    raw = f.read(count * 8)
xyzg = struct.unpack("<%dH" % (count * 4), raw)

rng = random.Random(783)  # the FlyWire release
by_node = {}
outside = []
for k in range(count):
    g = xyzg[k * 4 + 3]
    if g == NOT_IN_GRAPH:
        outside.append(k)
    else:
        by_node.setdefault(g, []).append(k)

chosen = []
for g in sorted(by_node):
    members = by_node[g]
    chosen += rng.sample(members, min(PER_NODE, len(members)))
rest = [k for g in by_node for k in by_node[g]]
chosen += rng.sample(rest, max(0, WIRED - len(chosen)))
chosen += rng.sample(outside, min(UNWIRED, len(outside)))


def quant(v):
    return round(v / 65535 * QUANT)


cloud = []
for k in chosen:
    g = xyzg[k * 4 + 3]
    cloud.append("%d %d %d %d" % (quant(xyzg[k * 4]), quant(xyzg[k * 4 + 1]), quant(xyzg[k * 4 + 2]),
                                  -1 if g == NOT_IN_GRAPH else g))


def wrap(words, width=118):
    lines, line, length = [], [], 0
    for w in words:
        if length + len(w) + 1 > width:
            lines.append(" ".join(line))
            line, length = [], 0
        line.append(w)
        length += len(w) + 1
    if line:
        lines.append(" ".join(line))
    return "\n".join(lines)


def lua_list(values):
    return "{ " + ", ".join(str(v) for v in values) + " }"


edge_words = []
for s, t, w, _ in edges:
    edge_words.append("%d %d %s" % (s, t, ("%.4f" % w).rstrip("0").rstrip(".")))
pos_words = ["%.3f %.3f %.3f" % tuple(nd["p"]) for nd in nodes]

with open(OUT, "w") as f:
    f.write("-- Generated by tools/build_flywire_data.py from flywire-swarm's data/: don't edit.\n")
    f.write("-- FlyWire v783 (Dorkenwald et al. 2024; Schlegel et al. 2024), edges after Shiu et al. 2024.\n")
    f.write("return {\n")
    f.write("    N = %d,\n" % len(nodes))
    f.write("    quant = %d,\n" % QUANT)
    f.write("    io = {\n")
    for key, value in io.items():
        f.write("        %s = %s,\n" % (key, lua_list(value)))
    f.write("    },\n")
    f.write("    oa = %s,\n" % lua_list(oa))
    f.write("    edges = [[\n%s\n]],\n" % wrap(edge_words))
    f.write("    positions = [[\n%s\n]],\n" % wrap(pos_words))
    f.write("    cloud = [[\n%s\n]],\n" % wrap(cloud))
    f.write("}\n")

print("nodes", len(nodes), "edges", len(edges), "cloud", len(cloud), "->", os.path.normpath(OUT),
      os.path.getsize(OUT), "bytes")
